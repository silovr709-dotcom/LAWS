/**
 * Формальная проверка черновика процессуального документа.
 *
 * Это не юридическая экспертиза и не оценка позиции. Функция ищет только
 * формальные признаки, по которым документы чаще всего возвращают или
 * оставляют без рассмотрения: адресат, данные заявителя, ссылка на норму,
 * дата события, просительная часть, приложения, подпись.
 *
 * Работает целиком в браузере: текст никуда не отправляется.
 */

export type DraftStatus = 'ok' | 'attention' | 'missing';

export type DraftCheck = {
  id: string;
  label: string;
  status: DraftStatus;
  hint: string;
  /** Куда посмотреть, если признак не найден. */
  link?: { href: string; label: string };
};

export type DraftReport = {
  words: number;
  /** Доля найденных формальных признаков, 0–100. */
  score: number;
  ready: boolean;
  checks: DraftCheck[];
  missing: DraftCheck[];
};

const has = (text: string, pattern: RegExp) => pattern.test(text);

const MONTHS =
  '(январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)';

export function inspectDraft(raw: string): DraftReport {
  const text = raw.replace(/\r/g, '').trim();
  const words = text ? (text.match(/[А-Яа-яЁёA-Za-z0-9-]+/g)?.length ?? 0) : 0;

  const addressee = has(text, /^\s*(?:в\s|прокурору|начальнику|руководителю|судье|председателю)/im) ||
    has(text, /(?:в\s+[^\n.]{0,90}(?:суд|прокуратур|отдел|управлен|орган|пристав))/i);

  const applicant =
    has(text, /(?:^|\n)\s*от\s+[А-ЯЁ][а-яё-]+/m) ||
    has(text, /(?:фио|фамилия|заявител|жалобщик|истец|ответчик|подозреваем|обвиняем|осужденн|представител)/i);

  const contacts = has(text, /(?:адрес|проживающ|зарегистрирован|телефон|почт[аеы]|e-?mail)/i);

  const law = has(text, /(?:ст\.?\s*\d|стать[яию]\s*\d|ч\.\s*\d|\b\d+\s*(?:УК|УПК|ГК|ГПК|КАС|СК|КоАП)\b)/i);

  const eventDate = has(text, /\b\d{1,2}[.\s](?:\d{1,2}|[а-яё]+)[.\s]\d{2,4}\b/i) ||
    new RegExp(`\\b\\d{1,2}\\s+${MONTHS}`, 'i').test(text);

  // Границы \b в JavaScript не работают с кириллицей, поэтому проверяем соседние символы.
  const request = has(text, /(?:^|[^а-яё])(?:прошу|просим|требую|требуем)(?![а-яё])/i);

  const demand = has(
    text,
    /(обязать|признать|отменить|изменить|взыскать|истребовать|возбудить|провести|восстановить|приостановить|освободить|допустить|ознакомить|направить|рассмотреть|устранить|выдать|назначить|считать|разъяснить|опросить|приобщить|вернуть|прекратить)/i,
  );

  const attachments = has(text, /приложени|прилагаю|приложение/i);

  const signature = has(text, /подпис[ьи]/i) || has(text, /(?:дата|«\s*\d{1,2}\s*»)/i);

  const appeal = has(text, /(?:жалоб|обжал|апелляц|кассац)/i);

  const emotion = has(
    text,
    /(нагл|беспредел|обман|враньё|вранье|ложь|лжёт|лжет|коррупц|некомпетент|хамств|бардак|издевательств|преступник[а-я]*\s+власт)/i,
  );

  const checks: DraftCheck[] = [
    {
      id: 'addressee',
      label: 'Кому адресован документ',
      status: addressee ? 'ok' : 'missing',
      hint: addressee
        ? 'Адресат указан в начале. Проверьте название органа и должность.'
        : 'В начале обычно пишут, кому адресован документ: суд, прокурор, руководитель органа. Без адресата документ может уйти не туда.',
      link: { href: '/materialy/obrazcy/', label: 'Посмотреть, как оформлены образцы' },
    },
    {
      id: 'applicant',
      label: 'Данные заявителя',
      status: applicant ? 'ok' : 'missing',
      hint: applicant
        ? 'Заявитель назван. Сверьте фамилию, имя и отчество с паспортом.'
        : 'Нужны фамилия, имя, отчество и процессуальный статус: заявитель, потерпевший, подозреваемый. Без этого документ сложно приобщить.',
      link: { href: '/materialy/obrazcy/', label: 'Образцы с реквизитами' },
    },
    {
      id: 'contacts',
      label: 'Адрес и способ связи',
      status: contacts ? 'ok' : 'attention',
      hint: contacts
        ? 'Контакт для ответа указан.'
        : 'Адрес для ответа и телефон помогают получить уведомление. В открытых каналах указывайте только то, без чего не обойтись.',
    },
    {
      id: 'law',
      label: 'Ссылка на норму',
      status: law ? 'ok' : 'missing',
      hint: law
        ? 'Норма права указана. Проверьте, что редакция статьи действует сейчас.'
        : 'Сошлитесь на конкретную статью и часть: «ч. 1 ст. 125 УПК РФ». Ссылка на норму показывает, что именно нарушено.',
      link: { href: '/materialy/razbory/', label: 'Разборы с нормами' },
    },
    {
      id: 'event',
      label: 'Дата и обстоятельства',
      status: eventDate ? 'ok' : 'missing',
      hint: eventDate
        ? 'Дата в тексте есть. Проверьте, что она совпадает с документами.'
        : 'Укажите дату события: когда задержали, изъяли, отказали. Без даты невозможно проверить сроки.',
      link: { href: '/48-chasov/', label: 'Счётчик сроков после задержания' },
    },
    {
      id: 'request',
      label: 'Просительная часть',
      status: request ? 'ok' : 'missing',
      hint: request
        ? 'Просьба сформулирована. Она должна быть выполнимой и относиться к этому органу.'
        : 'Любой документ заканчивается просьбой: «прошу…». Без неё непонятно, какое решение вы просите принять.',
      link: { href: '/materialy/obrazcy/', label: 'Как звучит просительная часть' },
    },
    {
      id: 'demand',
      label: 'Конкретное требование',
      status: request ? (demand ? 'ok' : 'attention') : 'missing',
      hint: request && demand
        ? 'В просьбе есть действие: обязать, признать, истребовать. Это то, что орган может выполнить.'
        : 'После «прошу» нужен глагол действия: обязать устранить, признать незаконным, истребовать документы. Просьба «разобраться» не обязывает ни к чему.',
    },
    {
      id: 'attachments',
      label: 'Приложения',
      status: attachments ? 'ok' : 'attention',
      hint: attachments
        ? 'Приложения перечислены. Проверьте, что копии действительно приложены.'
        : 'Перечислите копии документов, на которые ссылаетесь. Если приложений нет, так и напишите.',
    },
    {
      id: 'signature',
      label: 'Подпись и дата',
      status: signature ? 'ok' : 'missing',
      hint: signature
        ? 'Место для подписи и даты есть.'
        : 'В конце — дата и подпись. Документ без подписи считается неподанным.',
    },
    {
      id: 'tone',
      label: 'Оценочные формулировки',
      status: emotion ? 'attention' : 'ok',
      hint: emotion
        ? 'В тексте есть оценки вроде «беспредел» или «ложь». Они не помогают: суд реагирует на факты, даты и нормы. Замените оценку описанием действия.'
        : 'Резких оценок не найдено. Факты и даты убедительнее характеристик.',
    },
  ];

  if (appeal) {
    checks.push({
      id: 'appeal-copy',
      label: 'Срок на обжалование',
      status: has(text, /(срок|10\s*сут|десяти\s*сут|восстанов)/i) ? 'ok' : 'attention',
      hint: 'Для жалобы важно указать, когда вы узнали о решении: от этого считается срок. Если срок пропущен — просите его восстановить и объясните причину.',
      link: { href: '/sroki/', label: 'Посчитать срок' },
    });
  }

  // Оценка считается по девяти обязательным признакам; дополнительные подсказки
  // (тон, срок обжалования) на балл не влияют.
  const core = new Set([
    'addressee',
    'applicant',
    'contacts',
    'law',
    'event',
    'request',
    'demand',
    'attachments',
    'signature',
  ]);
  const counted = checks.filter((item) => core.has(item.id));
  const found = counted.filter((item) => item.status === 'ok').length;
  const score = counted.length ? Math.round((found / counted.length) * 100) : 0;

  return {
    words,
    score,
    ready: score >= 80,
    checks,
    missing: checks.filter((item) => item.status !== 'ok'),
  };
}
